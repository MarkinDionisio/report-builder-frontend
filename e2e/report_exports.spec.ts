import { expect, test } from "@playwright/test";

for (const width of [1440, 390]) test(`exports and notifications at ${width}px`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: 900 });
  const json = (value: unknown) => ({ status: 200, contentType: "application/json", body: JSON.stringify(value) });
  await page.addInitScript(() => localStorage.setItem("report-builder.session.v1", JSON.stringify({ refreshToken: "refresh" })));
  await page.route("**/api/v1/**", route => route.fulfill(json({ data: [], totalCount: 0, unreadCount: 0 })));
  await page.route("**/api/v1/auth/refresh", route => route.fulfill(json({ accessToken: "token", refreshToken: "refresh", expiresAt: new Date(Date.now() + 3600000).toISOString() })));
  await page.route("**/api/v1/me", route => route.fulfill(json({ id: "user", name: "Pessoa", email: "pessoa@example.com", globalRole: "user", organizations: [], profileIds: [] })));
  const title = "Relatório de vendas e movimentações com nome extenso para validar o painel";
  await page.route("**/api/v1/reports/report", route => route.fulfill(json({ id: "report", title, organizationName: "Empresa", canExecute: true, content: { version: 1, parameters: [{ name: "store", label: "Filial", type: "string", source: "input", required: false }], dataset: { select: [{ fieldId: "amount", alias: "Total" }] } } })));
  await page.route("**/api/v1/reports/report/execute", route => route.fulfill(json({ columns: [{ alias: "Total", type: "number" }], rows: [{ Total: 10 }], rowCount: 1, page: 1, pageSize: 50, durationMs: 10, resolvedParameters: { store: "one" } })));
  let ready = false;
  let completed = false;
  let posted: unknown;
  const expiresAt = new Date(Date.now() + 86400000).toISOString();
  const job = () => ({ id: "job", reportId: "report", organizationId: "org", organizationName: "Empresa com nome extenso para identificação da organização de origem", title, format: "csv", status: completed ? "ready" : "queued", serviceStatus: completed ? "available" : "unavailable", createdAt: new Date(Date.now() - 40 * 60_000).toISOString(), expiresAt });
  await page.route("**/api/v1/reports/report/exports", route => { posted = route.request().postDataJSON(); ready = true; return route.fulfill({ ...json({ id: "job", status: "queued" }), status: 202 }); });
  await page.route("**/api/v1/report-exports?**", route => route.fulfill(json({ data: ready ? [job()] : [], totalCount: ready ? 1 : 0 })));
  await page.route("**/api/v1/report-exports/job", route => route.fulfill(json(job())));
  await page.route("**/api/v1/notifications?**", route => route.fulfill(json({ data: ready ? [{ id: "notice", jobId: "job", message: "Exportação disponível", createdAt: new Date().toISOString(), readAt: null }] : [], totalCount: ready ? 1 : 0, unreadCount: ready ? 1 : 0 })));
  await page.route("**/api/v1/report-exports/job/download", route => route.fulfill({ status: 200, contentType: "text/csv", headers: { "Content-Disposition": "attachment; filename=relatorio.csv" }, body: "Total\r\n10\r\n" }));
  let denyExport = true;
  await page.route("**/api/v1/reports/report/exports", async route => {
    if (denyExport) return route.fulfill({ ...json({ code: "export.global_template", status: 403 }), status: 403 });
    return route.fallback();
  });
  await page.goto("/reports/report/run");
  await page.getByLabel("Filial", { exact: true }).fill("one");
  await page.getByRole("button", { name: "Executar relatório", exact: true }).click();
  await expect(page.getByRole("button", { name: "Exportar dados" })).toBeEnabled();
  await page.getByRole("button", { name: "Exportar dados" }).click();
  await page.getByRole("button", { name: "CSV (.csv)" }).click();
  const alert = page.getByRole("alert");
  await expect(alert).toHaveText("Importe este modelo global para sua organização antes de exportar.");
  await expect(page.getByRole("button", { name: "Atualizar andamento" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("export-error.png"), fullPage: true, animations: "disabled" });
  denyExport = false;
  await page.getByRole("button", { name: "Exportar dados" }).click();
  await page.getByRole("button", { name: "CSV (.csv)" }).click();
  await expect(page.getByText("Exportação na fila")).toBeVisible();
  await expect(page.getByText(/O serviço de geração está indisponível/)).toBeVisible();
  if (width > 860) await expect.poll(async () => (await page.getByRole("heading", { name: title }).boundingBox())?.x ?? 0).toBeGreaterThanOrEqual(260);
  await page.screenshot({ path: testInfo.outputPath(`waiting-${width}.png`), fullPage: true, animations: "disabled" });
  expect(posted).toEqual({ format: "csv", parameters: { store: "one" }, filters: [] });
  completed = true;
  await page.evaluate(() => document.dispatchEvent(new Event("visibilitychange")));
  await expect(page.getByText("Arquivo pronto para baixar")).toBeVisible();
  await page.getByRole("button", { name: "Acompanhar exportações" }).click();
  const dialog = page.getByRole("dialog", { name: "Exportações e notificações" });
  await expect(dialog.getByText("CSV · Disponível")).toBeVisible();
  await expect(dialog.getByText("Organização: Empresa com nome extenso para identificação da organização de origem")).toBeVisible();
  await expect(dialog.getByText(/Disponível até/)).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath(`exports-${width}.png`), fullPage: true });
  const downloadEvent = page.waitForEvent("download");
  await dialog.getByRole("button", { name: "Baixar arquivo" }).click();
  expect((await downloadEvent).suggestedFilename()).toBe("relatorio.csv");
  await page.keyboard.press("Escape");
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole("button", { name: "Acompanhar exportações" })).toBeFocused();
  await page.getByLabel("Filial", { exact: true }).fill("two");
  await expect(page.getByRole("button", { name: "Exportar dados" })).toBeDisabled();
  await page.getByRole("button", { name: "Executar relatório", exact: true }).click();
  await expect(page.getByRole("button", { name: "Nova exportação" })).toBeEnabled();
  await expect(page.getByText("Exportação anterior deste relatório.")).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("new-execution.png"), fullPage: true, animations: "disabled" });
  await page.getByRole("button", { name: "Nova exportação" }).click();
  await page.getByRole("button", { name: "CSV (.csv)" }).click();
  await expect.poll(() => posted).toEqual({ format: "csv", parameters: { store: "two" }, filters: [] });
  await expect(page.getByText("Exportação anterior deste relatório.")).toHaveCount(0);
  await page.reload();
  await page.getByRole("button", { name: /Exportações e notificações/ }).click();
  await expect(page.getByRole("dialog").getByRole("button", { name: "Baixar arquivo" })).toBeVisible();
});
